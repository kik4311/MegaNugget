#!/usr/bin/env python3
"""Import a pinned, licensed upstream snapshot with explicit legacy adaptations.

Usage: python3 scripts/import_goldennugget_core.py /path/to/GoldenNugget-mobile
Requires the exact clean Git checkout below. No network access or git mutations.
Generated Swift files are compiled into MegaNuggetCore, not a second application.
"""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

REVISION = "e4be86f050f4980ccc58de3b74f9de58b070b705"
ROOT = Path(__file__).resolve().parents[1]
FILES = ["TweakCatalog.swift", "TweakCatalogDaemons.swift", "TweakModel.swift",
         "TweakDomainMap.swift", "TweakCompiler.swift"]
HEADER = """// SPDX-License-Identifier: AGPL-3.0
// Derived from GoldenNugget-Team/GoldenNugget-mobile, revision {revision}.
// Original authors and full credits: LICENSES/GoldenNuggetMobile-README.upstream.md.
// Modifications by MegaNugget contributors, 2026-11-06:
// Strict version parsing/gates; compiler restricted to explicitly selected specs.
// Imported for OFFLINE DRAFTS ONLY. No restore or system-write transport is included.
// Generated by scripts/import_goldennugget_core.py; see docs/GOLDENNUGGET_PORT.md.

"""


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError("Upstream changed: adaptation anchor is not unique")
    return text.replace(old, new, 1)


def adapt(name, text):
    if name == "TweakModel.swift":
        start = text.index("    private static func components(_ version: String)")
        end = text.index("    /// -1 / 0 / 1", start)
        text = text[:start] + '''    private static func components(_ version: String) -> [Int]? {
        let parts = version.split(separator: ".", omittingEmptySubsequences: false)
        guard (1...3).contains(parts.count) else { return nil }
        var result: [Int] = []
        for part in parts {
            guard !part.isEmpty, part.utf8.allSatisfy({ (48...57).contains($0) }),
                  let number = Int(part) else { return nil }
            result.append(number)
        }
        return result
    }

''' + text[end:]
        start = text.index("    func isCompatible(deviceVersion:")
        end = text.index("    /// Parse a `.number` edit", start)
        text = text[:start] + '''    func isCompatible(deviceVersion: String, isIPhone: Bool, deviceModel: String = "") -> Bool {
        // MegaNugget: fail closed, including unknown/malformed bounds and device OS.
        guard TweakVersion.compare(deviceVersion, deviceVersion) != nil else { return false }
        if disabled || unavailableReason != nil { return false }
        if !supportedModels.isEmpty && !supportedModels.contains(deviceModel) { return false }
        if let minimum = minVersion {
            guard let result = TweakVersion.compare(deviceVersion, minimum), result >= 0 else { return false }
        }
        if let maximum = maxVersion {
            guard let result = TweakVersion.compare(deviceVersion, maximum), result <= 0 else { return false }
        }
        if factory == "SiriAITweak" { return false } // Opaque archives not part of the legacy port.
        if ipadOnly && isIPhone { return false }
        if iphoneOnly && !isIPhone { return false }
        if requiresDynamicIsland && !TweakDeviceCapabilities.hasDynamicIsland(deviceModel) { return false }
        if requiresCameraControl && !TweakDeviceCapabilities.hasCameraControl(deviceModel) { return false }
        if requiresActionButton && !TweakDeviceCapabilities.hasActionButton(deviceModel) { return false }
        if requiresHomeButton && !TweakDeviceCapabilities.hasHomeButton(deviceModel) { return false }
        if requiresAlwaysOn && !TweakDeviceCapabilities.hasAlwaysOn(deviceModel) { return false }
        return true
    }

''' + text[end:]
    if name == "TweakCompiler.swift":
        text = replace_once(text, "        forcedDaemonKeys: Set<String> = []\n",
                            "        forcedDaemonKeys: Set<String> = [],\n        specs: [TweakSpec]\n")
        text = replace_once(text, "for spec in TweakCatalog.allWithDaemons where !spec.disabled",
                            "for spec in specs where !spec.disabled")
    return HEADER.format(revision=REVISION) + text


def main():
    source = Path(sys.argv[1]).resolve()
    revision = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=source, text=True).strip()
    dirty = subprocess.check_output(["git", "status", "--porcelain"], cwd=source, text=True)
    if revision != REVISION or dirty:
        raise SystemExit("Expected the pinned clean upstream checkout; refusing import.")
    outputs = {}
    upstream_hashes = {}

    def write(path, data):
        destination = ROOT / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
        outputs[path] = hashlib.sha256(data).hexdigest()

    for name in FILES:
        original = (source / "Nugget/Core" / name).read_bytes()
        upstream_hashes["Nugget/Core/" + name] = hashlib.sha256(original).hexdigest()
        write("apps/ios/Sources/Core/GoldenNuggetPort/" + name,
              adapt(name, original.decode()).encode())
    for src, dest in [("LICENSE", "LICENSES/GoldenNuggetMobile-AGPL-3.0.txt"),
                      ("README.md", "LICENSES/GoldenNuggetMobile-README.upstream.md"),
                      ("FORKING.md", "LICENSES/GoldenNuggetMobile-FORKING.upstream.md")]:
        data = (source / src).read_bytes()
        upstream_hashes[src] = hashlib.sha256(data).hexdigest()
        write(dest, data)
    manifest = {"repository": "https://github.com/GoldenNugget-Team/GoldenNugget-mobile",
                "revision": REVISION, "upstream_sha256": upstream_hashes, "outputs": outputs}
    (ROOT / "LICENSES/GoldenNuggetMobile-import.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Imported {len(FILES)} Swift files with provenance and complete upstream notices.")


if __name__ == "__main__":
    main()
